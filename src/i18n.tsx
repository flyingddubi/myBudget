type MessagesShape = typeof BASE_MESSAGES.ko;

export const MESSAGES = {
  ...BASE_MESSAGES,
  vi: BASE_MESSAGES["en-US"],
};

type I18nContextValue = {
  locale: AppLocale;
  setLocale: (locale: AppLocale) => void;
  localeTag: string;
  messages: MessagesShape;
  formatDate: (
    value: Date | string | number,
    options?: Intl.DateTimeFormatOptions,
  ) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function toLocaleTag(locale: AppLocale) {
  switch (locale) {
    case "ko":
      return "ko-KR";
    case "zh-TW":
      return "zh-TW";
    case "zh-CN":
      return "zh-CN";
    case "en-US":
      return "en-US";
    case "vi":
      return "vi-VN";
    case "ja-JP":
      return "ja-JP";
  }
}

export function I18nProvider({ children }: PropsWithChildren) {
  const [locale, setLocale] = useLocalStorage<AppLocale>(I18N_STORAGE_KEY, "ko");
  const localeTag = toLocaleTag(locale);

  useEffect(() => {
    setFormattingLocale(locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      localeTag,
      messages: MESSAGES[locale] as MessagesShape,
      formatDate: (value, options) =>
        new Date(value).toLocaleDateString(localeTag, options),
    }),
    [locale, localeTag, setLocale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) {
    throw new Error("useI18n must be used within I18nProvider");
  }
  return context;
}
